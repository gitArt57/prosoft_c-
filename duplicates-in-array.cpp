class Solution
{
public:
    // Возвращает true, если в массиве есть дубликаты, иначе false
    // Используем hash set для отслеживания уже встреченных элементов
    bool containsDuplicate(vector<int> &nums)
    {
        // Множество для хранения уже встреченных значений
        // unordered_set обеспечивает быструю проверку наличия элемента (в среднем O(1))
        unordered_set<int> seen;

        // Проходим по всем элементам массива
        for (int i = 0; i < nums.size(); i++)
        {
            // Текущий элемент, который проверяем на дубликат
            int current = nums[i];

            // Проверяем, встречали ли мы этот элемент раньше
            // seen.count(current) возвращает 1, если элемент есть в множестве, и 0 если нет
            if (seen.count(current) > 0)
            {
                // Элемент уже есть в множестве — найден дубликат
                // Можно сразу вернуть true, не проверяя остальные элементы
                return true;
            }

            // Элемент ещё не встречался — добавляем его в множество
            // Теперь при следующей встрече этого же элемента функция вернёт true
            seen.insert(current);
        }

        // Если цикл завершился и дубликатов не найдено — все элементы уникальны
        return false;
    }
};