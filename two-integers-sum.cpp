class Solution
{
public:
    // Возвращает сумму двух целых чисел без использования + и -
    // Используем побитовые операции: XOR для суммы без переноса, AND для переноса
    int getSum(int a, int b)
    {
        // Пока есть перенос (b != 0), продолжаем итерации
        while (b != 0)
        {
            // Вычисляем перенос: биты, где оба числа равны 1
            // Сдвигаем влево на 1, так как перенос идёт в старший разряд
            int carry = (a & b) << 1;

            // Сумма без учёта переноса: XOR складывает биты по правилу 1+1=0, 1+0=1
            a = a ^ b;

            // Перенос становится новым вторым слагаемым для следующей итерации
            b = carry;
        }

        // Когда переносов больше нет (b == 0), a содержит итоговую сумму
        return a;
    }
};